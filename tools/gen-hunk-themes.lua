--- Generates the nushu-dark/nushu-light Hunk themes from nushu's own palette.
---
---     nvim -l tools/gen-hunk-themes.lua

local repo = vim.fn.fnamemodify(vim.fn.resolve(debug.getinfo(1, "S").source:sub(2)), ":p:h:h")
package.path = repo .. "/lua/?.lua;" .. repo .. "/lua/?/init.lua;" .. package.path

local scope_rules = dofile(repo .. "/tools/textmate-scopes.lua")

---@param colors NushuColors
---@param variant "dark"|"light"
---@return { [1]: string, [2]: string }[] ordered key/value pairs
local function chrome(colors, variant)
    local ui, diff, vcs = colors.theme.ui, colors.theme.diff, colors.theme.vcs
    return {
        { "id", "nushu-" .. variant },
        { "label", variant == "dark" and "Nushu Dark" or "Nushu Light" },
        { "base", variant == "dark" and "github-dark-default" or "github-light-default" },
        { "background", ui.bg },
        { "panel", ui.bg_dim },
        { "panelAlt", ui.bg_p2 },
        { "border", ui.border },
        { "accent", vcs.changed },
        { "accentMuted", ui.word_write },
        { "text", ui.fg },
        { "muted", ui.nontext },
        { "contextBg", ui.bg },
        { "contextContentBg", ui.bg },
        { "addedBg", diff.add },
        { "removedBg", diff.delete },
        { "movedAddedBg", diff.change },
        { "movedRemovedBg", diff.change },
        { "addedContentBg", diff.text },
        { "removedContentBg", diff.text_delete },
        { "addedSignColor", vcs.added },
        { "removedSignColor", vcs.removed },
        { "lineNumberBg", ui.bg },
        { "lineNumberFg", ui.nontext },
        { "selectedHunk", ui.word_read },
        { "badgeAdded", vcs.added },
        { "badgeRemoved", vcs.removed },
        { "badgeNeutral", ui.nontext },
        { "fileNew", vcs.added },
        { "fileDeleted", vcs.removed },
        { "fileRenamed", vcs.changed },
        { "fileModified", vcs.changed },
        { "fileUntracked", vcs.untracked },
        { "noteBorder", ui.float.fg_border },
        { "noteBackground", ui.float.bg },
        { "noteTitleBackground", ui.bg_p2 },
        { "noteTitleText", ui.fg },
    }
end

---@param syn SyntaxElements
---@param fg string
local function syntax_scopes(syn, fg)
    local pairs_ = { { "source", fg } }
    for _, rule in ipairs(scope_rules(syn)) do
        for scope in rule[2]:gmatch("[^,%s]+") do
            pairs_[#pairs_ + 1] = { scope, rule[3] }
        end
    end
    return pairs_
end

--- Hand-written rather than vim.json.encode, which reorders keys and would turn every regeneration into a diff.
local function theme_js(colors, variant)
    local o = { "  {" }
    for _, kv in ipairs(chrome(colors, variant)) do
        o[#o + 1] = string.format("    %s: %q,", kv[1], kv[2])
    end
    o[#o + 1] = "    syntaxScopes: {"
    for _, kv in ipairs(syntax_scopes(colors.theme.syn, colors.theme.ui.fg)) do
        o[#o + 1] = string.format("      %q: %q,", kv[1], kv[2])
    end
    o[#o + 1] = "    },"
    o[#o + 1] = "  },"
    return table.concat(o, "\n")
end

local themes = {}
for _, variant in ipairs({ "dark", "light" }) do
    -- colors.lua memoizes the resolved theme on the nushu module; reset it or the light pass re-emits dark.
    package.loaded["nushu.colors"] = nil
    package.loaded["nushu.themes"] = nil
    local nushu = require("nushu")
    nushu._CURRENT_THEME = nil
    themes[#themes + 1] = theme_js(require("nushu.colors").setup({ theme = variant }), variant)
end

local out = table.concat({
    "// Nushu themes for Hunk — generated by tools/gen-hunk-themes.lua, do not edit by hand.",
    "// Regenerate with: nvim -l tools/gen-hunk-themes.lua",
    "",
    "const themes = [",
    table.concat(themes, "\n"),
    "];",
    "",
    "export default function (hunk) {",
    "  for (const theme of themes) hunk.registerTheme(theme);",
    "}",
    "",
}, "\n")

local path = repo .. "/extras/hunk/nushu/index.js"
vim.fn.mkdir(vim.fn.fnamemodify(path, ":h"), "p")
local f = assert(io.open(path, "w"), "cannot write " .. path)
f:write(out)
f:close()
io.write("wrote extras/hunk/nushu/index.js\n")
